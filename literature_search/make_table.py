"""Turn search_log.csv into the LaTeX table of the updated search (Section 3).

    python make_table.py ../../manuscript/tables/search_update.tex
"""

import csv
import sys

TOPIC = {
    "Q1": "Catastrophic forgetting in continual learning",
    "Q2": "Continual learning of large language models",
    "Q3": "Continual learning of vision-language / foundation / pre-trained models",
    "Q4": "Continual learning in spiking and neuromorphic networks",
    "Q5": "Plasticity-regulating mechanisms and forgetting",
    "Q6": "Class-incremental learning",
    "Q7": "Lifelong / sequential knowledge editing",
    "Q8": "Continual learning and hippocampus, sleep or CLS",
}


def tex(s: str) -> str:
    return s.replace('"', "\\char34{}").replace("|", "$\\vert$").replace("&", "\\&")  # \char34 = straight quote in typewriter font


def main(out):
    rows = list(csv.DictReader(open("search_log.csv", encoding="utf-8")))
    date = rows[0]["accessed"]
    lines = [
        "% generated by cl-benchmark/literature_search/make_table.py from search_log.csv",
        "\\begin{table}[h]",
        f"\\caption{{Queries of the updated literature search (Semantic Scholar, titles and abstracts, publication years {rows[0]['years'].replace('-', '--')}, accessed {date}). "
        "Phrases are in quotes; + denotes AND and $\\vert$ denotes OR.}\\label{tab:search-update}",
        "\\footnotesize",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep\\fill}lp{0.3\\textwidth}p{0.45\\textwidth}r}",
        "\\toprule",
        "ID & Topic & Query & Records \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(f"{r['id']} & {TOPIC[r['id']]} & {{\\ttfamily\\scriptsize {tex(r['query'])}}} & {int(r['hits']):,} \\\\")
    lines += ["\\botrule", "\\end{tabular*}", "\\end{table}", ""]
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1])
