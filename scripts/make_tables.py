"""Aggregate result files into the tables and figure of the paper.

    python scripts/make_tables.py --results kaggle/out/cifar100/results kaggle/out/mnist/results \
        --tables ../manuscript/tables --figures ../manuscript/figures --summary results_summary

Writes
  <tables>/exp_hparams.tex   hyper-parameter grids and selected values
  <tables>/exp_results.tex   final average accuracy and backward transfer (mean +- sd over seeds)
  <tables>/exp_memory.tex    persistent memory and measured cost (timing runs)
  <figures>/fig16_results.pdf/.png  accuracy on the tasks seen so far after each task
  <summary>/summary.csv, summary.json  all metrics, for the text and the repository
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

COLS = [("splitmnist", "task"), ("splitmnist", "domain"), ("splitmnist", "class"), ("permmnist", "domain"),
        ("splitcifar100", "task"), ("splitcifar100", "class")]
COLNAME = {("splitmnist", "task"): "S-MNIST Task-IL", ("splitmnist", "domain"): "S-MNIST Domain-IL",
           ("splitmnist", "class"): "S-MNIST Class-IL", ("permmnist", "domain"): "P-MNIST Domain-IL",
           ("splitcifar100", "task"): "S-CIFAR-100 Task-IL", ("splitcifar100", "class"): "S-CIFAR-100 Class-IL"}
ROWS = ["finetune", "ewc", "si", "lwf", "er", "dgr", "owm", "pnn", "mer", "snn-finetune", "snn-ewc", "snn-er", "joint"]
ROWNAME = {"finetune": "Fine-tuning (lower bound)", "joint": "Joint (upper bound)", "ewc": "EWC", "si": "SI", "lwf": "LwF",
           "er": "ER", "dgr": "DGR", "owm": "OWM", "pnn": "PNN", "mer": "MER", "snn-finetune": "SNN fine-tuning",
           "snn-ewc": "SNN + EWC", "snn-er": "SNN + ER"}
HP_LABEL = {"ewc_lambda": r"$\lambda$", "si_c": r"$c$", "owm_alpha": r"$\alpha$", "lr": "lr", "mer_beta": r"$\beta$"}


def load(dirs, phase):
    out = defaultdict(list)
    for d in dirs:
        for f in Path(d, phase).rglob("seed*.json"):
            r = json.loads(f.read_text())
            c = r["config"]
            name = c["method"] if c["arch"] != "snn" else f"snn-{c['method']}"
            out[(c["benchmark"], c["scenario"], name)].append(r)
    return out


def ms(vals, scale=100.0, digits=1):
    v = np.array(vals, dtype=float) * scale
    if len(v) == 0 or np.all(np.isnan(v)):
        return None
    return float(np.nanmean(v)), float(np.nanstd(v, ddof=1)) if len(v) > 1 else 0.0


def fmt(x, digits=1, bold=False):
    if x is None:
        return "--"
    s = f"{x[0]:.{digits}f}\\,$\\pm$\\,{x[1]:.{digits}f}"
    return f"\\textbf{{{s}}}" if bold else s


def summary(final):
    rows = []
    for (b, s, m), runs in sorted(final.items()):
        rec = {"benchmark": b, "scenario": s, "method": m, "n_seeds": len(runs)}
        for k in ("ACC", "AIA", "BWT", "FM", "FWT"):
            vals = [r["metrics"].get(k, np.nan) for r in runs]
            v = ms(vals)
            rec[k] = None if v is None else round(v[0], 2)
            rec[k + "_sd"] = None if v is None else round(v[1], 2)
        rows.append(rec)
    return rows


def results_table(final):
    acc = {(b, s, m): ms([r["metrics"]["ACC"] for r in runs]) for (b, s, m), runs in final.items()}
    bwt = {(b, s, m): ms([r["metrics"].get("BWT", np.nan) for r in runs]) for (b, s, m), runs in final.items()}
    best = {}
    for col in COLS:
        cands = [(acc[(*col, m)][0], m) for m in ROWS if m != "joint" and (*col, m) in acc and acc[(*col, m)]]
        best[col] = max(cands)[1] if cands else None
    seeds = sorted({len(runs) for runs in final.values()})
    lines = ["% generated by cl-benchmark/scripts/make_tables.py", "\\begin{table}[h]",
             "\\caption{Average accuracy after the last task (ACC, \\%; mean $\\pm$ standard deviation over "
             f"{'/'.join(map(str, seeds))} seeds) and backward transfer (BWT, \\%) of representative methods. S-MNIST = Split MNIST, "
             "P-MNIST = Permuted MNIST, S-CIFAR-100 = Split CIFAR-100. Best continual method per column in bold (joint training "
             "is an upper bound). PNN needs the task identity and is evaluated in Task-IL only; the spiking network (SNN) was "
             "evaluated on the MNIST benchmarks. -- = not applicable.}\\label{tab:exp-results}",
             "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\begin{tabular*}{\\textwidth}{@{\\extracolsep\\fill}l" + "c" * len(COLS) + "}", "\\toprule",
             "Method & " + " & ".join(COLNAME[c].replace(" ", "\\\\[-1pt] ", 1).join(["\\makecell{", "}"]) for c in COLS) + " \\\\",
             "\\midrule", "\\multicolumn{" + str(len(COLS) + 1) + "}{l}{\\emph{ACC (\\%)}}\\\\"]
    for m in ROWS:
        cells = [fmt(acc.get((*c, m)), bold=(best[c] == m)) for c in COLS]
        if m == "joint":
            lines.append("\\midrule")
        lines.append(ROWNAME[m] + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\midrule", "\\multicolumn{" + str(len(COLS) + 1) + "}{l}{\\emph{BWT (\\%)}}\\\\"]
    for m in ROWS:
        if m == "joint":
            continue
        cells = [fmt(bwt.get((*c, m))) for c in COLS]
        lines.append(ROWNAME[m] + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\botrule", "\\end{tabular*}", "\\end{table}", ""]
    return "\n".join(lines)


def hparam_table(hp_dirs, grids, snn_grids):
    sel = {}
    for d in hp_dirs:
        p = Path(d, "selected_hparams.json")
        if p.exists():
            sel.update(json.loads(p.read_text()))

    def val(v):
        return f"{v:g}" if isinstance(v, float) else str(v)

    lines = ["% generated by cl-benchmark/scripts/make_tables.py", "\\begin{table}[h]",
             "\\caption{Hyper-parameter grids and the values selected on the validation sets (seed 0) for each benchmark and scenario.}\\label{tab:exp-hparams}",
             "\\scriptsize", "\\begin{tabular*}{\\textwidth}{@{\\extracolsep\\fill}llp{0.5\\textwidth}}", "\\toprule",
             "Method & Grid & Selected value (benchmark / scenario) \\\\", "\\midrule"]
    for m, grid in list(grids.items()) + [("snn-" + k, v) for k, v in snn_grids.items()]:
        gtxt = "; ".join(f"{HP_LABEL.get(k, k)} $\\in\\{{{', '.join(val(x) for x in v)}\\}}$" for k, v in grid.items())
        picks = []
        for key in sorted(sel):
            b, s, name = key.split("/")
            if name == m:
                picks.append(f"{COLNAME.get((b, s), key)}: " + ", ".join(f"{HP_LABEL.get(k, k)}={val(v)}" for k, v in sel[key].items()))
        lines.append(f"{ROWNAME.get(m, m)} & {gtxt} & {'; '.join(picks) or '--'} \\\\")
    lines += ["\\botrule", "\\end{tabular*}", "\\end{table}", ""]
    return "\n".join(lines)


def cost_tables(timing, final):
    bench_cols = [("splitmnist", "class"), ("permmnist", "domain"), ("splitcifar100", "task")]
    lines = ["% generated by cl-benchmark/scripts/make_tables.py", "\\begin{table}[h]",
             "\\caption{Measured cost of each method (seed 1, one job per GPU, NVIDIA T4): training time per task (s), its ratio to "
             "fine-tuning, peak GPU memory during training (MB) and size of the persistent state kept in addition to the network (MB). "
             "Split CIFAR-100 is measured in Task-IL, and PNN on Split MNIST in Task-IL; the cost of the other methods does not depend on the scenario.}\\label{tab:exp-cost}",
             "\\scriptsize", "\\setlength{\\tabcolsep}{2.5pt}",
             "\\begin{tabular*}{\\textwidth}{@{\\extracolsep\\fill}l" + "rrrr" * len(bench_cols) + "}", "\\toprule",
             " & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{COLNAME[c]}}}" for c in bench_cols) + " \\\\",
             " ".join(f"\\cmidrule{{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(len(bench_cols))),
             "Method & " + " & ".join(["s/task & $\\times$FT & GPU & state"] * len(bench_cols)) + " \\\\", "\\midrule"]
    for m in ROWS:
        cells = []
        for b, s in bench_cols:
            sc = "task" if m == "pnn" else s  # PNN needs task identity -> measured in Task-IL
            runs = timing.get((b, sc, m)) or []
            ft = timing.get((b, sc, "finetune")) or []
            if not runs:
                cells += ["--"] * 4
                continue
            r = runs[0]
            tpt = r["train_time_s"] / len(r["time_per_task_s"]) if m != "joint" else r["train_time_s"] / len(r["b"])
            ratio = (r["train_time_s"] / ft[0]["train_time_s"]) if ft else float("nan")
            cells += [f"{tpt:.1f}", f"{ratio:.1f}", f"{r['peak_gpu_mem_mb']:.0f}", f"{r['extra_state_mb']:.1f}"]
        lines.append(ROWNAME[m] + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\botrule", "\\end{tabular*}", "\\end{table}", ""]
    return "\n".join(lines)


def memory_table(timing):
    # analytic persistent memory for the CIFAR-100 ConvNet (P parameters) and the measured state size
    rows = [
        ("EWC", "$2tP$", "ewc"), ("SI", "$\\approx 4P$", "si"), ("OWM", "$\\sum_\\ell n_\\ell^2$", "owm"),
        ("LwF", "$P$", "lwf"), ("ER", "$Md$", "er"), ("DGR", "$P+2P_G$", "dgr"), ("PNN", "$(t-1)P+\\tfrac{t(t-1)}{2}P_{\\mathrm{lat}}$", "pnn"),
        ("MER", "$Md$", "mer"),
    ]
    lines = ["% generated by cl-benchmark/scripts/make_tables.py", "\\begin{table}[h]",
             "\\caption{Persistent memory kept in addition to the network, from the cost model of Table~\\ref{tab:cost-model}, and its "
             "measured size (MB, float32) after the last task in our benchmark. $P$ is the number of parameters of the backbone "
             "(0.48\\,M for the Split MNIST MLP, 1.8\\,M for the Permuted MNIST MLP, 1.14\\,M for the Split CIFAR-100 ConvNet).}\\label{tab:memory}",
             "\\scriptsize", "\\begin{tabular*}{\\textwidth}{@{\\extracolsep\\fill}llrrr}", "\\toprule",
             "Method & Persistent extra memory & S-MNIST & P-MNIST & S-CIFAR-100 \\\\", "\\midrule"]
    for name, formula, m in rows:
        cells = []
        for b, s in [("splitmnist", "class"), ("permmnist", "domain"), ("splitcifar100", "task")]:
            key = (b, "task", m) if m == "pnn" else (b, s, m)
            runs = timing.get(key) or []
            cells.append(f"{runs[0]['extra_state_mb']:.1f}" if runs else "--")
        lines.append(f"{name} & {formula} & " + " & ".join(cells) + " \\\\")
    lines += ["\\botrule", "\\end{tabular*}", "\\end{table}", ""]
    return "\n".join(lines)


def figure(final, out: Path):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    panels = [("splitmnist", "class"), ("permmnist", "domain"), ("splitcifar100", "task"), ("splitcifar100", "class")]
    methods = ["finetune", "ewc", "si", "lwf", "er", "dgr", "owm", "mer", "pnn", "snn-er"]
    colors = dict(zip(methods, ["#7f7f7f", "#1f77b4", "#17becf", "#9467bd", "#d62728", "#ff7f0e", "#2ca02c", "#8c564b", "#e377c2", "#bcbd22"]))
    fig, axes = plt.subplots(1, len(panels), figsize=(4 * len(panels), 3.2))
    for ax, (b, s) in zip(axes, panels):
        for m in methods:
            runs = final.get((b, s, m))
            if not runs:
                continue
            curves = []
            for r in runs:
                R = np.array(r["R"], dtype=float)
                curves.append([np.nanmean(R[t, : t + 1]) for t in range(R.shape[0])])
            c = np.array(curves) * 100
            x = np.arange(1, c.shape[1] + 1)
            ax.plot(x, c.mean(0), "-o", ms=3, color=colors[m], label=ROWNAME[m])
            ax.fill_between(x, c.mean(0) - c.std(0), c.mean(0) + c.std(0), color=colors[m], alpha=0.15)
        ax.set_title(COLNAME[(b, s)], fontsize=10)
        ax.set_xlabel("Number of tasks learned")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("Average accuracy on tasks seen (%)")
    handles, labels = [], []
    for ax in axes:
        for h, l in zip(*ax.get_legend_handles_labels()):
            if l not in labels:
                handles.append(h)
                labels.append(l)
    fig.legend(handles, labels, loc="lower center", ncol=len(labels), fontsize=8, frameon=False)
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(out.with_suffix(".pdf"))
    fig.savefig(out.with_suffix(".png"), dpi=200)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", nargs="+", required=True)
    ap.add_argument("--tables", required=True)
    ap.add_argument("--figures", required=True)
    ap.add_argument("--summary", required=True)
    a = ap.parse_args()
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from clbench.configs import HP_GRIDS, SNN_HP_GRIDS

    final = load(a.results, "final")
    timing = load(a.results, "timing")
    tables, figs, summ = Path(a.tables), Path(a.figures), Path(a.summary)
    for p in (tables, figs, summ):
        p.mkdir(parents=True, exist_ok=True)
    (tables / "exp_results.tex").write_text(results_table(final), encoding="utf-8")
    (tables / "exp_hparams.tex").write_text(hparam_table(a.results, HP_GRIDS, SNN_HP_GRIDS), encoding="utf-8")
    (tables / "exp_memory.tex").write_text(memory_table(timing) + "\n" + cost_tables(timing, final), encoding="utf-8")
    figure(final, figs / "fig16_results")
    rows = summary(final)
    (summ / "summary.json").write_text(json.dumps(rows, indent=1))
    import csv

    with open(summ / "summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    t = []
    for (b, s, m), runs in sorted(timing.items()):
        r = runs[0]
        t.append({"benchmark": b, "scenario": s, "method": m, "train_time_s": round(r["train_time_s"], 1),
                  "peak_gpu_mem_mb": round(r["peak_gpu_mem_mb"], 1), "extra_state_mb": round(r["extra_state_mb"], 2)})
    (summ / "timing.json").write_text(json.dumps(t, indent=1))
    print(f"final configs: {len(final)}, timing configs: {len(timing)}")


if __name__ == "__main__":
    main()
